const assert = require('assert')
const fs = require('fs')
const path = require('path')
const batch = require('../features/data/web-recipes-202611')
const { BUILTIN_RECIPES } = require('../data/recipes')
const { getBuiltinRecipe } = require('../features/data/recipe-details')
const health = require('../utils/health')
const { getBuiltinCartoonCover } = require('../utils/image-service')
const cloudIndex = require('../cloudfunctions/recipeCommunity/builtin-category-index')

assert.strictEqual(batch.length, 15)
const summaries = new Map(BUILTIN_RECIPES.map(recipe => [recipe.id, recipe]))
const ids = new Set()
const names = new Set()
BUILTIN_RECIPES.forEach(recipe => {
  assert(!ids.has(recipe.id), `重复 ID：${recipe.id}`)
  assert(!names.has(recipe.name), `重复菜名：${recipe.name}`)
  ids.add(recipe.id)
  names.add(recipe.name)
})

batch.forEach(item => {
  const summary = summaries.get(item.id)
  const recipe = getBuiltinRecipe(item.id)
  assert(summary && recipe, `${item.id} 必须同时存在于首页索引和详情数据中`)
  assert.strictEqual(summary.name, item.name)
  assert.strictEqual(summary.createdAt, 1793577600000)
  assert.strictEqual(summary.energyLevel, 'unknown')
  assert.strictEqual(summary.estimatedKcalPerServing, null)
  assert.strictEqual(summary.healthEligible, false)
  assert.strictEqual(recipe.healthEligible, false)
  assert.strictEqual(recipe.sourceLicense, 'CC BY-SA 4.0')
  assert.strictEqual(recipe.sourceLicenseUrl, 'https://creativecommons.org/licenses/by-sa/4.0/')
  assert(/^https:\/\/en\.wikibooks\.org\/wiki\/Cookbook:/.test(recipe.referenceUrl))
  assert(/&oldid=\d+$/.test(recipe.referenceRevisionUrl), `${item.id} 缺少核对版本`)
  assert(recipe.ingredients.length >= 3 && recipe.steps.length >= 4)
  assert(recipe.servings > 0 && recipe.durationMinutes > 0)
  assert.deepStrictEqual(summary.steps, [], '首页仍然只保留轻量摘要')
  assert.deepStrictEqual(summary.ingredients, [], '完整食材明细不得进入主包')
  assert(recipe.steps.every((step, index) => step.order === index + 1 && step.text.length > 15))
  assert(!recipe.videoUrl && !recipe.sourceCoverCloudPath)
  assert(recipe.steps.every(step => !step.image && step.imageCloudPaths.length === 0))
  const cover = getBuiltinCartoonCover(recipe)
  assert(cover && fs.existsSync(path.resolve(__dirname, '..', '.' + cover)), `${item.id} 缺少本地封面降级`)
  assert(cloudIndex.some(row => row[0] === item.id && row[1] === item.name), '同步生成管理员归类索引')

  recipe.allergens.forEach(allergen => {
    const results = health.filterRecipesByDietaryRestrictions([summary], { allergies: [allergen], avoidedIngredients: [] })
    assert.strictEqual(results.length, 0, `${item.name} 未过滤过敏原 ${allergen}`)
  })
  const avoided = recipe.ingredients[0].name
  assert.strictEqual(health.filterRecipesByDietaryRestrictions([summary], { allergies: [], avoidedIngredients: [avoided] }).length, 0)
})

assert(getBuiltinRecipe('w026').allergens.includes('豆制品'))
assert(getBuiltinRecipe('w026').allergens.includes('小麦或麸质'))
assert(getBuiltinRecipe('w024').allergens.includes('花生与坚果'))
assert(getBuiltinRecipe('w016').durationMinutes >= 240, '等待时间包含冷藏沥水和入味')
console.log(`网页菜谱测试通过：新增 ${batch.length} 道，总计 ${BUILTIN_RECIPES.length} 道；来源、详情、过滤、封面和轻量索引有效`)
